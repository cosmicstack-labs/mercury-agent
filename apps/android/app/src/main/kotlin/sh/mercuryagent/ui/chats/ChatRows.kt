@Composable
fun RenameDialog(initial: String, onDismiss: () -> Unit, onSave: (String) -> Unit) {
  var name by remember { mutableStateOf(initial) }
  AlertDialog(
    onDismissRequest = onDismiss,
    title = { Text("Rename chat") },
    text = {
      Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
        Text("Up to 120 characters. Mercury keeps the name you choose.", style = MaterialTheme.typography.bodyMedium)
        OutlinedTextField(name, { name = it.take(120) }, singleLine = true, label = { Text("Chat name") })
      }
    },
    confirmButton = { TextButton(onClick = { onSave(name) }, enabled = name.isNotBlank()) { Text("Save") } },
    dismissButton = { TextButton(onClick = onDismiss) { Text("Cancel") } },
  )
}
