#!/usr/bin/env node
/**
 * Compile the multi-file built-in skills in src/skills/bundled/<name>/ into
 * src/skills/bundled-skills.generated.ts, so their scripts ship inside the
 * bundle (npm, standalone binaries) without any loader or extra files.
 *
 *   node scripts/gen-bundled-skills.cjs          # regenerate
 *   node scripts/gen-bundled-skills.cjs --check  # fail if out of date (tests run this)
 */
const { readdirSync, readFileSync, statSync, writeFileSync, existsSync } = require('node:fs');
const { join, relative, sep } = require('node:path');

const ROOT = join(__dirname, '..');
const SRC = join(ROOT, 'src', 'skills', 'bundled');
const OUT = join(ROOT, 'src', 'skills', 'bundled-skills.generated.ts');

function walk(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    if (name.startsWith('.') || name === '__pycache__') return [];
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

function generate() {
  const skills = readdirSync(SRC).sort().filter((n) => statSync(join(SRC, n)).isDirectory());
  const entries = skills.map((dirName) => {
    const files = {};
    for (const p of walk(join(SRC, dirName))) files[relative(join(SRC, dirName), p).split(sep).join('/')] = readFileSync(p, 'utf8');
    if (!files['SKILL.md']) throw new Error(`${dirName}: no SKILL.md`);
    return { dirName, files };
  });
  return `// GENERATED by scripts/gen-bundled-skills.cjs from src/skills/bundled/ — do not edit.\n`
    + `// Regenerate with: node scripts/gen-bundled-skills.cjs\n\n`
    + `export interface BundledSkill {\n  dirName: string;\n  /** Path inside the skill folder → contents. Always includes SKILL.md. */\n  files: Record<string, string>;\n}\n\n`
    + `export const BUNDLED_SKILLS: BundledSkill[] = ${JSON.stringify(entries, null, 2)};\n`;
}

const next = generate();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== next) {
    console.error('src/skills/bundled-skills.generated.ts is out of date: run node scripts/gen-bundled-skills.cjs');
    process.exit(1);
  }
  console.log('bundled skills up to date');
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${relative(ROOT, OUT)} (${Math.round(next.length / 1024)} KB)`);
}
