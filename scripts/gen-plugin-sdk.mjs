// Regenerates src/plugins/sdk-dts.ts from src/plugins/sdk.ts so that
// `mercury plugins init` (which runs inside a compiled binary with no
// source files around) can write the Plugin API types into new plugins.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const sdk = readFileSync(`${root}src/plugins/sdk.ts`, 'utf8');
const out = `// Generated by scripts/gen-plugin-sdk.mjs from src/plugins/sdk.ts. Do not edit.\nexport const PLUGIN_SDK_DTS = ${JSON.stringify(sdk)};\n`;
writeFileSync(`${root}src/plugins/sdk-dts.ts`, out);
console.log('wrote src/plugins/sdk-dts.ts');
